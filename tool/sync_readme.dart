void main() {
  final readme = File('README.md');
  if (!readme.existsSync()) {
    stderr.writeln('README.md not found. Run from project root.');
    exit(1);
  }
  var text = readme.readAsStringSync();
  final buf = StringBuffer();
  buf.writeln(
      '> This block is generated by `dart tool/sync_readme.dart`. **Do not edit by hand.**');
  buf.writeln(
      '> Any feature change in `lib/` must re-run the sync so README stays truthful.');
  buf.writeln();
  buf.writeln('| # | Feature | Where | Status |');
  buf.writeln('|---|---------|-------|--------|');
  for (var i = 0; i < features.length; i++) {
    final f = features[i];
    buf.writeln('| ${i + 1} | ${f.name} | ${f.where} | ${f.status} |');
  }
  final block = buf.toString().trimRight();
  final start = '<!-- FEATURES:START -->';
  final end = '<!-- FEATURES:END -->';
  final sIdx = text.indexOf(start);
  final eIdx = text.indexOf(end);
  if (sIdx == -1 || eIdx == -1 || eIdx < sIdx) {
    stderr.writeln('FEATURES markers missing in README.md');
    exit(1);
  }
  final before = text.substring(0, sIdx + start.length);
  final after = text.substring(eIdx);
  final next = '$before\n\n$block\n\n$after';
  readme.writeAsStringSync(next);
  stdout.writeln('README features synced (${features.length} features).');
}
